const LANGS = ['en', 'zh']

/** Saved choice wins if valid; else Chinese for any zh-* browser language; else English. */
export function pickLang(saved, navLang) {
  if (LANGS.includes(saved)) return saved
  return String(navLang || '').toLowerCase().startsWith('zh') ? 'zh' : 'en'
}

function defaultStorage() {
  try {
    return globalThis.localStorage ?? null
  } catch {
    return null
  }
}

export function readSavedLang(storage = defaultStorage()) {
  try {
    return storage?.getItem('lang') ?? null
  } catch {
    return null
  }
}

export function saveLang(lang, storage = defaultStorage()) {
  try {
    storage?.setItem('lang', lang)
  } catch {
    /* storage blocked: the choice lasts for this page view only */
  }
}

/** Look up a string and replace {name} placeholders. */
export function t(lang, key, vars = {}) {
  const s = T[lang][key] ?? T.en[key] ?? ''
  return s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m))
}

export function applyLang(doc, lang) {
  doc.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en'
  doc.title = t(lang, 'name')
  const meta = doc.querySelector('meta[name="description"]')
  if (meta) meta.setAttribute('content', t(lang, 'metaDesc'))
  doc.querySelectorAll('[data-i]').forEach((el) => { el.textContent = t(lang, el.dataset.i) })
  doc.querySelectorAll('[data-h]').forEach((el) => { el.innerHTML = t(lang, el.dataset.h) })
  doc.querySelectorAll('[data-aria]').forEach((el) => {
    el.setAttribute('aria-label', t(lang, el.dataset.aria, { n: el.dataset.n ?? '' }))
  })
  doc.querySelectorAll('[data-alt]').forEach((el) => { el.setAttribute('alt', t(lang, el.dataset.alt)) })
  doc.querySelectorAll('.lang [data-l]').forEach((b) => {
    const on = b.dataset.l === lang
    b.classList.toggle('on', on)
    b.setAttribute('aria-pressed', String(on))
  })
}
