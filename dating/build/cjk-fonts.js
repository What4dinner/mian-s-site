// Build-time CJK font trimming.
// The Chinese font packages ship hundreds of unicode-range slices. Declaring all of them
// costs ~200 KB of render-blocking CSS, so we keep only the @font-face rules whose range
// covers a character the page actually uses. The browser then downloads only those slices.
import fs from 'node:fs'
import path from 'node:path'
import { createRequire } from 'node:module'

/** "U+20, U+4E00-4E3F, U+4??" → [[0x20,0x20],[0x4e00,0x4e3f],[0x400,0x4ff]] */
export function parseUnicodeRange(value) {
  return value.split(',').map((part) => {
    const p = part.trim().replace(/^U\+/i, '')
    if (p.includes('?')) return [parseInt(p.replace(/\?/g, '0'), 16), parseInt(p.replace(/\?/g, 'F'), 16)]
    const [a, b = a] = p.split('-')
    return [parseInt(a, 16), parseInt(b, 16)]
  })
}

/** Set of code points used by the given strings. */
export function pageChars(strings) {
  const set = new Set()
  for (const s of strings) for (const ch of s) set.add(ch.codePointAt(0))
  return set
}

/**
 * Keep @font-face blocks that have no unicode-range or whose range covers any char in `chars`.
 * `rewriteUrl` maps each url() inside kept blocks (used to point at node_modules).
 */
export function filterFontFaces(css, chars, rewriteUrl = (u) => u) {
  const codes = [...chars]
  const blocks = css.match(/@font-face\s*\{[^}]*\}/g) || []
  return blocks
    .filter((block) => {
      const m = block.match(/unicode-range\s*:\s*([^;}]+)/i)
      if (!m) return true
      const ranges = parseUnicodeRange(m[1])
      return codes.some((c) => ranges.some(([a, b]) => c >= a && c <= b))
    })
    .map((block) => block.replace(/url\(\s*(['"]?)([^'")]+)\1\s*\)/g, (_, q, u) => `url("${rewriteUrl(u)}")`))
    .join('\n')
}

const require = createRequire(import.meta.url)

/** CSS files of the Chinese fonts to trim. */
const SOURCES = [
  '@chinese-fonts/lxgwwenkai/dist/LXGWWenKai-Medium/result.css',
  '@fontsource/noto-sans-sc/400.css',
  '@fontsource/noto-sans-sc/500.css',
]

/** Writes `outFile` with trimmed @font-face rules for every char in `strings`. Returns rule count. */
export function writeCjkCss(strings, outFile) {
  const chars = pageChars(strings)
  const outDir = path.dirname(outFile)
  const parts = SOURCES.map((spec) => {
    const file = require.resolve(spec)
    const dir = path.dirname(file)
    const css = fs.readFileSync(file, 'utf8')
    return filterFontFaces(css, chars, (u) => path.relative(outDir, path.resolve(dir, u)).split(path.sep).join('/'))
  })
  const body = parts.join('\n')
  fs.writeFileSync(outFile, '/* Generated by build/cjk-fonts.js — do not edit. */\n' + body + '\n')
  return (body.match(/@font-face/g) || []).length
}

/** Vite plugin: regenerates the trimmed CJK font CSS from the page copy + index.html before each build/dev start. */
export function cjkFonts({ root, outFile, getStrings }) {
  const run = () => {
    const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8')
    writeCjkCss([...getStrings(), html], outFile)
  }
  return { name: 'cjk-fonts', config: run }
}
